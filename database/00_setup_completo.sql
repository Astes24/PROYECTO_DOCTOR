-- Trigger para evitar traslapes de turnos en el consultorio
CREATE OR REPLACE FUNCTION check_overlap_horarios() 
RETURNS trigger AS $$
BEGIN
  -- Buscamos si existe OTRO turno en la misma fecha que choque con el nuevo rango
  IF EXISTS (
    SELECT 1 FROM horarios_diarios 
    WHERE fecha_exacta = NEW.fecha_exacta 
    AND (id != NEW.id OR NEW.id IS NULL) -- Blindaje para nuevos INSERTs
    AND (NEW.hora_inicio < hora_fin AND NEW.hora_fin > hora_inicio) -- Lógica de intersección exacta
  ) THEN
    -- Si encontramos un choque, cancelamos y lanzamos error
    RAISE EXCEPTION 'El nuevo horario se solapa con un turno existente en el consultorio.';
  END IF;
  
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trigger_check_overlap_horarios ON horarios_diarios;
CREATE TRIGGER trigger_check_overlap_horarios
BEFORE INSERT OR UPDATE ON horarios_diarios
FOR EACH ROW EXECUTE FUNCTION check_overlap_horarios();

