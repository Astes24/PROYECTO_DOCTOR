-- 1. TABLA PACIENTES
-- Almacena la información base de tus usuarios.
CREATE TABLE IF NOT EXISTS pacientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    
    -- Columna 'dni' soporta DNI (8 dígitos), Carné de Extranjería (CE) y Pasaportes.
    -- Se recomienda almacenar todo en mayúsculas y sin guiones.
    dni VARCHAR(20) UNIQUE,              
    
    nombre_completo VARCHAR(150),        -- Nombre proporcionado por el usuario
    fecha_nacimiento DATE,               -- Para verificar edad si es necesario
    telefono_principal VARCHAR(20),      -- Número de WhatsApp (ID de usuario)
    email VARCHAR(100),                  -- Opcional
    
    descripcion TEXT,                    -- Opcional (Antes historia_clinica)
    fecha_modificacion TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()), -- Fecha de modificación de datos del paciente
    bot_activo BOOLEAN DEFAULT true      -- Permite pausar el bot para intervención humana (CRM)
);

-- Trigger para actualizar fecha_modificacion en pacientes
CREATE OR REPLACE FUNCTION update_paciente_modificacion()
RETURNS TRIGGER AS $$
BEGIN
    NEW.fecha_modificacion = timezone('utc'::text, now());
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trigger_update_paciente_modificacion ON pacientes;
CREATE TRIGGER trigger_update_paciente_modificacion
BEFORE UPDATE ON pacientes
FOR EACH ROW
EXECUTE FUNCTION update_paciente_modificacion();

-- 1.5 TABLA HISTORIAL CLINICO
-- Almacena cada entrada del historial clínico por paciente
CREATE TABLE IF NOT EXISTS historial_clinico (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dni_paciente VARCHAR(20) REFERENCES pacientes(dni) ON DELETE CASCADE,
    historia TEXT NOT NULL,
    archivos JSONB DEFAULT '[]'::jsonb,  -- Almacena array de objetos con info de archivos adjuntos
    estado_cerrado BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    fecha_modificacion TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Trigger para actualizar fecha_modificacion en historial_clinico
CREATE OR REPLACE FUNCTION update_historial_modificacion()
RETURNS TRIGGER AS $$
BEGIN
    NEW.fecha_modificacion = timezone('utc'::text, now());
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trigger_update_historial_modificacion ON historial_clinico;
CREATE TRIGGER trigger_update_historial_modificacion
BEFORE UPDATE ON historial_clinico
FOR EACH ROW
EXECUTE FUNCTION update_historial_modificacion();

-- 2. TABLA CITAS
-- Calendario de reservas. Simple y directa.
CREATE TABLE IF NOT EXISTS citas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    
    -- Relación con Paciente
    paciente_id BIGINT REFERENCES pacientes(id) ON DELETE SET NULL,
    
    -- Datos de la Cita
    fecha DATE NOT NULL,                 -- YYYY-MM-DD
    hora TIME NOT NULL,                  -- HH:MM:SS
    
    -- Estado: 'PENDIENTE', 'CONFIRMADA', 'REALIZADA', 'CANCELADA', 'NO_ASISTIO'
    estado VARCHAR(20) DEFAULT 'PENDIENTE',
    recordatorio_enviado BOOLEAN DEFAULT FALSE, -- Para el Cron de Recordatorios (24h)
    
    -- Metadatos de origen
    origen VARCHAR(20) DEFAULT 'BOT',    -- 'BOT', 'MANUAL', 'WEB'
    motivo_consulta TEXT                 -- Opcional
);

-- 3. TABLA NOTIFICACIONES (Sistema de Alertas Internas)
CREATE TABLE IF NOT EXISTS notificaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    
    mensaje TEXT NOT NULL,               -- Contenido de la alerta
    tipo VARCHAR(50) DEFAULT 'ALERTA_BOT', -- 'ALERTA_BOT', 'URGENCIA', 'FARMACIA'
    leido BOOLEAN DEFAULT FALSE,         -- Para que el Frontend marque como VISTO
    completado BOOLEAN DEFAULT FALSE,    -- Para que el frontend marque como SOLUCIONADO
    
    telefono_paciente VARCHAR(20)
);

-- 4. TABLA HISTORIAL_CHAT (Memoria del Bot)
CREATE TABLE IF NOT EXISTS historial_chat (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    
    id_sesion VARCHAR(50) NOT NULL,      -- Número de teléfono del usuario
    rol VARCHAR(20) NOT NULL,            -- 'user' o 'model'
    contenido TEXT,                      
    
    tipo_mensaje VARCHAR(20) DEFAULT 'text', 
    metadatos JSONB DEFAULT '{}'::jsonb  
);

-- 5. TABLA DE USUARIOS DEL PANEL (Control de Acceso al Frontend)
CREATE TABLE IF NOT EXISTS usuarios_panel (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
